CREATE TABLE IF NOT EXISTS BETTERJOBS_DB.STAGE.SKILL_STANDARDIZATION_RULES (
	RULE_ID VARCHAR(16777216) NOT NULL,
	PATTERN VARCHAR(16777216),
	STANDARDIZED_NAME VARCHAR(16777216),
	SKILL_CATEGORY VARCHAR(16777216),
	SKILL_SUBCATEGORY VARCHAR(16777216),
	CONFIDENCE_SCORE FLOAT DEFAULT 1,
	RULE_TYPE VARCHAR(16777216) DEFAULT 'exact_match',
