CREATE TABLE IF NOT EXISTS BETTERJOBS_DB.STAGE.TRANSFORMATION_LOGS (
	LOG_ID VARCHAR(16777216) NOT NULL,
	JOB_ID VARCHAR(16777216),
	TRANSFORMATION_STEP VARCHAR(16777216),
	STATUS VARCHAR(16777216),
	ERROR_MESSAGE VARCHAR(16777216),
	PROCESSING_TIME_SECONDS FLOAT,
	TIMESTAMP TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (LOG_ID)
);